for (const [route, title] of [['fx-docs', 'Валютные документы'], ['rub-docs', 'Рублёвые документы']] as const) {
  test(`${title}: перетаскивание в меню меняет порядок, галочка скрывает реквизит`, async ({ page }) => {
    await page.goto(`/?noauto#/${route}`)
    const grid = page.getByRole('grid', { name: title })
    const headers = grid.getByRole('columnheader')
    const before = await headers.allTextContents()
    expect(before.length).toBeGreaterThan(2)
    await grid.getByRole('button', { name: 'Состав колонок' }).click()
    const menu = page.getByRole('dialog', { name: 'Состав колонок' })
    const handles = menu.locator('[draggable=true]')
    const first = await handles.first().getAttribute('title')
    const second = await handles.nth(1).getAttribute('title')
    await handles.nth(1).dragTo(handles.first(), { targetPosition: { x: 4, y: 2 } })
    await expect(handles.first()).toHaveAttribute('title', second!)
    await expect(handles.nth(1)).toHaveAttribute('title', first!)
    await expect(headers.nth(1)).toHaveText(before[2]!)
    await expect(headers.nth(2)).toHaveText(before[1]!)
    const visible = await menu.getByRole('status').textContent()
    await menu.getByRole('checkbox').first().uncheck()
    await expect(menu.getByRole('status')).not.toHaveText(visible!)
    await expect(headers).toHaveCount(before.length - 1)
    await page.keyboard.press('Escape')
    await grid.getByRole('button', { name: 'Состав колонок' }).click()
    await expect(menu.getByRole('checkbox').first()).not.toBeChecked()
  })
}
