import { expect, test } from '@playwright/test'

test('два смонтированных реестра: скрытый не запрашивает данные, показ запрашивает один свежий срез', async ({ page }) => {
  await page.goto('/e2e/fixtures/registries.html')
  const a = page.getByTestId('calls-a')
  const b = page.getByTestId('calls-b')
  await expect(a).toHaveText(JSON.stringify({ search: 1, facets: 1, meta: 1, suggest: 0 }))
  await expect(b).toHaveText(JSON.stringify({ search: 0, facets: 0, meta: 0, suggest: 0 }))
  await expect(page.getByRole('grid', { name: 'Реестр A' })).toBeVisible()
  await expect(page.getByRole('grid', { name: 'Реестр B', includeHidden: true })).toBeHidden()
  await page.getByRole('button', { name: 'Поменять параметры B', exact: true }).click()
  await expect(b).toHaveText(JSON.stringify({ search: 0, facets: 0, meta: 0, suggest: 0 }))
  await page.getByRole('button', { name: 'Реестр B', exact: true }).click()
  await expect(b).toHaveText(JSON.stringify({ search: 1, facets: 1, meta: 1, suggest: 0 }))
  await expect(page.getByTestId('query-b')).toHaveText(JSON.stringify({ filter: [{ field: 'status', op: 'EQ', value: 'ERROR' }], sort: [{ key: 'status', dir: 'desc' }], page: 2, size: 50 }))
  await page.getByRole('button', { name: 'Обновить оба', exact: true }).click()
  await expect(a).toHaveText(JSON.stringify({ search: 1, facets: 1, meta: 1, suggest: 0 }))
  await expect(b).toHaveText(JSON.stringify({ search: 2, facets: 2, meta: 1, suggest: 0 }))
  await page.getByRole('button', { name: 'Закрыть страницу', exact: true }).click()
  await page.getByRole('button', { name: 'Обновить оба', exact: true }).click()
  await expect(b).toHaveText(JSON.stringify({ search: 2, facets: 2, meta: 1, suggest: 0 }))
  await page.getByRole('button', { name: 'Открыть страницу', exact: true }).click()
  await expect(b).toHaveText(JSON.stringify({ search: 3, facets: 3, meta: 1, suggest: 0 }))
})
