import { createGlobalStyle } from '../styled'
import { valueHot } from '../value/value.hot'
import { gridHot } from '../grid/grid.hot'

/**
 * Стили горячего пути грида (спека styled §4.3, правило 2): всё, что рисуется в каждой записи, — обычные элементы
 * с постоянными классами k-<часть>, а их правила объявлены один раз здесь, без styled-обёртки на каждом элементе
 * (опыт spike/styled, §3: только так реестр укладывается в порог скорости 15 %).
 *
 * Правила ограничены корнем провайдера: `:where([data-k-root]) .k-…` — префикс не добавляет специфичности,
 * она как у прежних правил CSS Modules. Монтирует KatranProvider; при нескольких провайдерах у каждого свой
 * экземпляр, правила остаются, пока жив хотя бы один. Модуль импортируется после корня провайдера: группа
 * этих стилей стоит в листе позже правил корня, а styled(Компонент) потребителя — позже неё и перебивает её.
 */
export const HotStyles = createGlobalStyle`
  :where([data-k-root]) {
    ${valueHot}
    ${gridHot}
  }
`
