import { TagInput, type TagInputProps } from './TagInput'

function Host({ initial = [], onValue = () => {}, onText = () => {}, ...p }: Partial<TagInputProps> & { initial?: string[]; onValue?: (v: string[]) => void; onText?: (t: string) => void }) {
  const [v, setV] = useState<string[]>(initial)
  const [t, setT] = useState('')
  return <TagInput aria-label="Номер документа" mode="values" {...p} value={v} onChange={(x) => { setV(x); onValue(x) }} text={t} onTextChange={(x) => { setT(x); onText(x) }} />
}
const chipsOf = (name: string) => within(screen.getByRole('list', { name })).getAllByRole('listitem').map((li) => li.firstChild?.textContent)
const chips = () => chipsOf('Номер документа')
const paste = (el: HTMLElement, text: string) => fireEvent.paste(el, { clipboardData: { getData: () => text } })

/** Поле с подсказками: список задаёт тест, владелец убирает его по onSuggestClose, как модель фильтров. */
function Suggest({ items = ['ЗАО «Василёк»', 'ООО «Ромашка»'], loading = false, initial = [], onQuery = () => {}, onSuggestClose = () => {}, onValue = () => {} }: {
  items?: string[]; loading?: boolean; initial?: string[]; onQuery?: (q: string) => void; onSuggestClose?: () => void; onValue?: (v: string[]) => void
}) {
  const [v, setV] = useState<string[]>(initial)
  const [t, setT] = useState('')
  const [shown, setShown] = useState(false)
  return (
    <TagInput aria-label="Приказодатель" mode="phrases" value={v} onChange={(x) => { setV(x); onValue(x) }} text={t} onTextChange={setT}
      suggestions={shown ? items : []} loading={shown && loading}
      onQuery={(q) => { setShown(q !== ''); onQuery(q) }} onSuggestClose={() => { setShown(false); onSuggestClose() }} />
  )
}

