describe('TagInput: подсказки', () => {
  it('комбобокс; список не открывается фокусом, открывается вводом; ↓ и Enter добавляют чип, закрытие сообщает onSuggestClose', async () => {
    const u = userEvent.setup()
    const onQuery = vi.fn()
    const onSuggestClose = vi.fn()
    renderK(<Suggest onQuery={onQuery} onSuggestClose={onSuggestClose} />)
    const box = screen.getByRole('combobox', { name: 'Приказодатель' })
    expect(box).toHaveAttribute('aria-autocomplete', 'list')
    await u.click(box)
    expect(onQuery).not.toHaveBeenCalled()
    expect(box).toHaveAttribute('aria-expanded', 'false')
    expect(box).not.toHaveAttribute('aria-controls')
    await u.type(box, 'ва')
    expect(onQuery).toHaveBeenLastCalledWith('ва')
    const list = screen.getByRole('listbox', { name: 'Подсказки: Приказодатель' })
    expect(box).toHaveAttribute('aria-expanded', 'true')
    expect(box).toHaveAttribute('aria-controls', list.id)
    expect(box).not.toHaveAttribute('aria-activedescendant')
    await u.keyboard('{ArrowDown}')
    expect(box).toHaveAttribute('aria-activedescendant', within(list).getAllByRole('option')[0]!.id)
    await u.keyboard('{Enter}')
    expect(chipsOf('Приказодатель')).toEqual(['ЗАО «Василёк»'])
    expect(box).toHaveValue('')
    expect(onSuggestClose).toHaveBeenCalled()
    expect(screen.queryByRole('listbox')).not.toBeInTheDocument()
  })
  it('Enter без активной подсказки делает чип из набранного', async () => {
    const u = userEvent.setup()
    renderK(<Suggest />)
    await u.type(screen.getByRole('combobox', { name: 'Приказодатель' }), 'ва{Enter}')
    expect(chipsOf('Приказодатель')).toEqual(['ва'])
  })
  it('клик по подсказке добавляет её; совпадение выделено полужирным', async () => {
    const u = userEvent.setup()
    renderK(<Suggest />)
    await u.type(screen.getByRole('combobox', { name: 'Приказодатель' }), 'ром')
    const opt = screen.getByRole('option', { name: 'ООО «Ромашка»' })
    expect(within(opt).getByText('Ром').tagName).toBe('B')
    fireEvent.click(opt)
    expect(chipsOf('Приказодатель')).toEqual(['ООО «Ромашка»'])
  })
  it('Escape закрывает список и сообщает onSuggestClose; ↓ открывает снова', async () => {
    const u = userEvent.setup()
    const onSuggestClose = vi.fn()
    const onQuery = vi.fn()
    renderK(<Suggest onSuggestClose={onSuggestClose} onQuery={onQuery} />)
    const box = screen.getByRole('combobox', { name: 'Приказодатель' })
    await u.type(box, 'ва')
    await u.keyboard('{Escape}')
    expect(screen.queryByRole('listbox')).not.toBeInTheDocument()
    expect(onSuggestClose).toHaveBeenCalledTimes(1)
    expect(box).toHaveValue('ва')
    await u.keyboard('{ArrowDown}')
    expect(onQuery).toHaveBeenLastCalledWith('ва')
    expect(screen.getByRole('listbox')).toBeInTheDocument()
  })
  it('загрузка без подсказок — «Ищу…»; пустой ответ — список закрыт', async () => {
    const u = userEvent.setup()
    const { rerender } = renderK(<Suggest items={[]} loading />)
    const box = screen.getByRole('combobox', { name: 'Приказодатель' })
    await u.type(box, 'ва')
    const list = screen.getByRole('listbox', { name: 'Подсказки: Приказодатель' })
    expect(within(list).getByRole('option')).toHaveTextContent('Ищу…')
    expect(within(list).getByRole('option')).toHaveAttribute('aria-disabled', 'true')
    await u.keyboard('{ArrowDown}{Enter}')
    expect(chipsOf('Приказодатель')).toEqual(['ва'])
    rerender(<Suggest items={[]} />)
    await u.type(box, 'ро')
    expect(screen.queryByRole('listbox')).not.toBeInTheDocument()
    expect(box).toHaveAttribute('aria-expanded', 'false')
  })
  it('подсказки, уже стоящие чипами, не показываются (фразы — без учёта регистра)', async () => {
    const u = userEvent.setup()
    renderK(<Suggest initial={['зао «василёк»']} />)
    await u.type(screen.getByRole('combobox', { name: 'Приказодатель' }), 'о')
    expect(screen.getAllByRole('option').map((o) => o.textContent)).toEqual(['ООО «Ромашка»'])
  })
  it('уход фокуса закрывает список', async () => {
    const u = userEvent.setup()
    const onSuggestClose = vi.fn()
    renderK(<><Suggest onSuggestClose={onSuggestClose} /><button type="button">после</button></>)
    await u.type(screen.getByRole('combobox', { name: 'Приказодатель' }), 'ва')
    await u.tab()
    expect(screen.queryByRole('listbox')).not.toBeInTheDocument()
    expect(onSuggestClose).toHaveBeenCalled()
  })
})

