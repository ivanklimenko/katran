import { fitTabs } from './fitTabs'

describe('fitTabs (эталон fitTabs, index.html:1089)', () => {
  it('всё помещается — все вкладки', () => {
    expect(fitTabs([100, 100, 100], 300, 40, 0)).toEqual([0, 1, 2])
  })
  it('не помещается — хвост уходит, место под «••• N» учтено', () => {
    expect(fitTabs([100, 100, 100, 100], 330, 40, 0)).toEqual([0, 1])
  })
  it('выбранная из хвоста остаётся видимой вместо предыдущих', () => {
    expect(fitTabs([100, 100, 100, 100], 330, 40, 3)).toEqual([0, 3])
  })
  it('зазор между вкладками учитывается', () => {
    expect(fitTabs([100, 100, 100], 310, 40, 0, 10)).toEqual([0, 1])
    expect(fitTabs([100, 100, 100], 320, 40, 0, 10)).toEqual([0, 1, 2])
  })
  it('совсем тесно — видна хотя бы выбранная', () => {
    expect(fitTabs([100, 100, 100], 50, 40, 2)).toEqual([2])
    expect(fitTabs([100, 100, 100], 50, 40, -1)).toEqual([0])
  })
  it('разделитель групп считается, только когда видны обе группы', () => {
    // все три с разделителем: 300 + 20 > 310 — хвост уходит, хотя без разделителя всё помещалось бы
    expect(fitTabs([100, 100, 100], 310, 40, 0, 0, { at: 2, width: 20 })).toEqual([0, 1])
    expect(fitTabs([100, 100, 100], 320, 40, 0, 0, { at: 2, width: 20 })).toEqual([0, 1, 2])
    // видна одна группа — разделителя нет, как без него
    expect(fitTabs([100, 100, 100, 100], 330, 40, 0, 0, { at: 3, width: 20 })).toEqual([0, 1])
    // выбранная из второй группы: разделитель встаёт перед ней и вытесняет ещё одну вкладку
    expect(fitTabs([100, 100, 100, 100], 330, 40, 3, 0, { at: 3, width: 20 })).toEqual([0, 3])
    expect(fitTabs([100, 100, 100, 100], 360, 40, 3, 0, { at: 3, width: 20 })).toEqual([0, 1, 3])
    // зазор стоит и по обе стороны разделителя
    expect(fitTabs([100, 100], 219, 40, 0, 5, { at: 1, width: 10 })).toEqual([0])
    expect(fitTabs([100, 100], 220, 40, 0, 5, { at: 1, width: 10 })).toEqual([0, 1])
  })
})
